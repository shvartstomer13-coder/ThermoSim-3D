"""Generate thermophysical tables from CoolProp (Helmholtz EOS: IAPWS-95, Tillner-Roth&Baehr R134a,
Lemmon R410A pseudo-pure, Melinder MEG). Output: src/physics/data/*.ts
Units: T[K] P[kPa] h[kJ/kg] s[kJ/kg/K] v[m3/kg] cp[kJ/kg/K] mu[Pa s] k[W/m/K]
"""
import sys, os, math
import numpy as np
import CoolProp.CoolProp as CP
from CoolProp.CoolProp import PropsSI

OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'physics', 'data')
os.makedirs(OUT, exist_ok=True)

def fmt(a):
    return '[' + ','.join('%.7g' % float(x) for x in a) + ']'

DT_LIST = [0,0.5,1,2,3,5,7.5,10,15,20,30,40,60,80,110,150,200,260,330,420,520,650,800]

def gen_real(key, fl, Tmin, Tmax, Tvmax, ref, M):
    if ref == 'IIR':
        CP.set_reference_state(fl, 'IIR')
    Tn = np.arange(Tmin, Tmax + 1e-9, 2.0)
    def sat(T, Q, what):
        return PropsSI(what, 'T', T, 'Q', Q, fl)
    cols = {k: [] for k in ['P','hf','hg','sf','sg','vf','vg','cpf','cpg','muf','mug','kf','kg']}
    for T in Tn:
        cols['P'].append(sat(T,0,'P')/1e3)
        cols['hf'].append(sat(T,0,'H')/1e3); cols['hg'].append(sat(T,1,'H')/1e3)
        cols['sf'].append(sat(T,0,'S')/1e3); cols['sg'].append(sat(T,1,'S')/1e3)
        cols['vf'].append(1/sat(T,0,'D')); cols['vg'].append(1/sat(T,1,'D'))
        cols['cpf'].append(sat(T,0,'C')/1e3); cols['cpg'].append(sat(T,1,'C')/1e3)
        cols['muf'].append(sat(T,0,'V')); cols['mug'].append(sat(T,1,'V'))
        cols['kf'].append(sat(T,0,'L')); cols['kg'].append(sat(T,1,'L'))
    if ref != 'IIR':  # water: h=s=0 at triple-point saturated liquid
        h0, s0 = cols['hf'][0], cols['sf'][0]
        for k in ('hf','hg'): cols[k] = [x - h0 for x in cols[k]]
        for k in ('sf','sg'): cols[k] = [x - s0 for x in cols[k]]
    else:
        h0 = s0 = 0.0
    # vapour grid: pressure nodes at every 2nd saturation temperature
    Tp = Tn[::2]
    nP, nD = len(Tp), len(DT_LIST)
    H = np.zeros((nP,nD)); S = np.zeros((nP,nD)); R = np.zeros((nP,nD)); MU = np.zeros((nP,nD)); K = np.zeros((nP,nD))
    Pn = []
    for i,Ts in enumerate(Tp):
        P = PropsSI('P','T',Ts,'Q',1,fl); Pn.append(P/1e3)
        valid = []
        for j,d in enumerate(DT_LIST):
            T = Ts + d
            if T > Tvmax and j > 0:
                valid.append(False); continue
            if d == 0:
                h = PropsSI('H','T',Ts,'Q',1,fl); s = PropsSI('S','T',Ts,'Q',1,fl); rho = PropsSI('D','T',Ts,'Q',1,fl)
                mu = PropsSI('V','T',Ts,'Q',1,fl); k = PropsSI('L','T',Ts,'Q',1,fl)
            else:
                h = PropsSI('H','T',T,'P',P,fl); s = PropsSI('S','T',T,'P',P,fl); rho = PropsSI('D','T',T,'P',P,fl)
                mu = PropsSI('V','T',T,'P',P,fl); k = PropsSI('L','T',T,'P',P,fl)
            H[i,j] = h/1e3 - h0; S[i,j] = s/1e3 - s0; R[i,j] = rho; MU[i,j] = mu; K[i,j] = k
            valid.append(True)
        # linear extrapolation for invalid tail (unreachable states, keeps monotonic tables)
        last = max(j for j,v in enumerate(valid) if v)
        for j in range(last+1, nD):
            f = (DT_LIST[j]-DT_LIST[last])/(DT_LIST[last]-DT_LIST[last-1])
            for A in (H,S,MU,K): A[i,j] = A[i,last] + f*(A[i,last]-A[i,last-1])
            R[i,j] = max(R[i,last]*0.5, R[i,last] + f*(R[i,last]-R[i,last-1]))
    Tc = PropsSI('Tcrit', fl); Pc = PropsSI('pcrit', fl)/1e3
    with open(os.path.join(OUT, key + '.ts'), 'w') as f:
        f.write('// GENERATED by scripts/gen_tables.py from CoolProp %s (%s). Do not edit.\n' % (CP.get_global_param_string('version'), fl))
        f.write("import type { RealFluidData } from '../types';\n")
        f.write('export const %s_DATA: RealFluidData = {\n' % key.upper())
        f.write("  id:'%s', M:%g, Tc:%.4f, Pc:%.3f, T0:%.4f, dT:2,\n" % (key, M, Tc, Pc, Tn[0]))
        for k,v in cols.items(): f.write('  %s:%s,\n' % (k, fmt(v)))
        f.write('  vap:{ Pn:%s, dTs:%s,\n' % (fmt(Pn), fmt(DT_LIST)))
        for nm,A in (('H',H),('S',S),('R',R),('MU',MU),('K',K)):
            f.write('    %s:%s,\n' % (nm, fmt(A.flatten())))
        f.write('  },\n};\n')
    print(key, 'sat rows', len(Tn), 'vap grid', nP, 'x', nD)

def gen_glycol(fl='INCOMP::MEG[0.3]', key='glycol30', const='GLYCOL30_DATA', Mmix=62.07*0.3+18.015*0.7, note='30 % mass ethylene glycol, Melinder', T0=263.15):
    Ts = np.arange(T0, 373.15 + 1e-9, 5.0)
    rho, cp, mu, k = [], [], [], []
    for T in Ts:
        rho.append(PropsSI('D','T',T,'P',101325,fl)); cp.append(PropsSI('C','T',T,'P',101325,fl)/1e3)
        mu.append(PropsSI('V','T',T,'P',101325,fl)); k.append(PropsSI('L','T',T,'P',101325,fl))
    try:
        tf = PropsSI('T_freeze','P',101325,'T',300,fl)
    except Exception:
        tf = 259.0
    with open(os.path.join(OUT, key + '.ts'), 'w') as f:
        f.write('// GENERATED by scripts/gen_tables.py from CoolProp (%s = %s). Do not edit.\n' % (fl, note))
        f.write("import type { LiquidFluidData } from '../types';\n")
        f.write('export const %s: LiquidFluidData = {\n' % const)
        f.write("  id:'%s', M:%g, T0:%.2f, dT:5, Tfreeze:%.2f, rho:%s, cp:%s, mu:%s, k:%s,\n};\n" % (key, Mmix, Ts[0], tf, fmt(rho), fmt(cp), fmt(mu), fmt(k)))
    print('glycol rows', len(Ts), 'Tfreeze', tf)

if __name__ == '__main__':
    gen_real('water', 'Water', 273.16, 620.0, 1073.15, 'DEF', 18.015)
    gen_real('r134a', 'R134a', 233.15, 360.0, 423.15, 'IIR', 102.03)
    gen_real('r410a', 'R410A', 233.15, 335.0, 423.15, 'IIR', 72.585)
    gen_glycol()
    gen_glycol('INCOMP::MPG[0.25]', 'pg25', 'PG25_DATA', 76.09*0.25+18.015*0.75, '25 % mass propylene glycol, Melinder', 268.15)
